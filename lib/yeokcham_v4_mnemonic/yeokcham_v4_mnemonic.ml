module Hash = Yeokcham_hash.Sha256

type error =
  | Unsupported_entropy_length of int
  | Invalid_word_count of int
  | Unknown_word of string
  | Invalid_checksum
  | Noncanonical_phrase

let error_to_string = function
  | Unsupported_entropy_length length ->
      Printf.sprintf "BIP-39 entropy must contain 16 or 32 bytes, got %d" length
  | Invalid_word_count count ->
      Printf.sprintf "BIP-39 phrase must contain 12 or 24 words, got %d" count
  | Unknown_word word -> "unknown BIP-39 English word: " ^ word
  | Invalid_checksum -> "BIP-39 mnemonic checksum is invalid"
  | Noncanonical_phrase -> "BIP-39 mnemonic phrase is not canonical"

