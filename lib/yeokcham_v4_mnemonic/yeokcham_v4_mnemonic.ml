let checksum_bits entropy =
  match String.length entropy with
  | 16 -> Ok 4
  | 32 -> Ok 8
  | length -> Error (Unsupported_entropy_length length)

let bit bytes position =
  let byte = Char.code bytes.[position / 8] in
  (byte lsr (7 - (position mod 8))) land 1

let phrase_for_entropy entropy =
  let* checksum_length = checksum_bits entropy in
  let digest = Hash.digest_string entropy |> Hash.to_raw_string in
  let total_entropy_bits = (String.length entropy * 8) + checksum_length in
  let index_at offset =
    let value = ref 0 in
    for index = 0 to 10 do
      let position = offset + index in
      let next =
        if position < String.length entropy * 8 then bit entropy position
        else bit digest (position - (String.length entropy * 8))
      in
      value := (!value lsl 1) lor next
    done;
    !value
  in
  let count = total_entropy_bits / 11 in
  Ok
    (Array.init count (fun index -> words.(index_at (index * 11)))
    |> Array.to_list |> String.concat " ")

let encode entropy = phrase_for_entropy entropy

let index_of_word word =
  let rec loop index =
    if index = Array.length words then None
    else if String.equal words.(index) word then Some index
    else loop (index + 1)
  in
  loop 0

let decode phrase =
  let phrase_words = String.split_on_char ' ' phrase in
  let* entropy_length =
    match List.length phrase_words with
    | 12 -> Ok 16
    | 24 -> Ok 32
    | count -> Error (Invalid_word_count count)
  in
  let* indices =
    let rec loop reversed = function
      | [] -> Ok (List.rev reversed)
      | word :: rest -> (
          match index_of_word word with
          | Some index -> loop (index :: reversed) rest
          | None -> Error (Unknown_word word))
    in
    loop [] phrase_words
  in
  let total_entropy_bits = entropy_length * 8 in
  let entropy = Bytes.make entropy_length '\000' in
  List.iteri
    (fun word_index value ->
      for bit_index = 0 to 10 do
        let position = (word_index * 11) + bit_index in
        if position < total_entropy_bits
           && ((value lsr (10 - bit_index)) land 1) = 1
        then
          let byte = position / 8 in
          let current = Char.code (Bytes.get entropy byte) in
          Bytes.set entropy byte
            (Char.chr (current lor (1 lsl (7 - (position mod 8)))))
      done)
    indices;
  let entropy = Bytes.unsafe_to_string entropy in
  let* canonical = phrase_for_entropy entropy in
  if String.equal canonical phrase then Ok entropy
  else
    let digest = Hash.digest_string entropy |> Hash.to_raw_string in
    let expected_checksum_bits = total_entropy_bits / 32 in
    let last = List.hd (List.rev indices) in
    let supplied = last land ((1 lsl expected_checksum_bits) - 1) in
    let expected = ref 0 in
    for index = 0 to expected_checksum_bits - 1 do
      expected := (!expected lsl 1) lor bit digest index
    done;
    if supplied <> !expected then Error Invalid_checksum else Error Noncanonical_phrase
